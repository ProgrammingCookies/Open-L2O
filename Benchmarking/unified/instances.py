"""The one LASSO instance loader.

Merges three copies of the same file-reading logic:
  * ``Model_Free_L2O/L2O-DM and L2O-RNNProp/problems.py`` (lasso_from_dataset)
  * ``Model_Free_L2O/L2O-Scale/problems/problem_generator.py`` (pg.Lasso)
  * ``Model_Base_L2O/data_preprocessing.py`` (input_fn)
all of which read the layout written by ``Benchmarking/data/lasso.py``:

  <data_dir>/A.npy              (m, n) shared dictionary
  <data_dir>/<split>.npy        rows ``[b (m,); x_true (n,)]`` float32
  <data_dir>/<split>_x0.npy     (num_samples, n) seeded starting point
  <data_dir>/W.npy              ALISTA's analytic weight (optional)

Two access patterns, matching the libraries exactly:
  * ``walk(batch_size)``   -- evaluation: every row exactly once, in file
                              order, ``batch_size`` rows at a time.
  * ``sample(batch_size)`` -- training: a fresh batch with replacement drawn
                              from the GLOBAL ``np.random`` state, so a seeded
                              unified run consumes the RNG the same way the
                              library scripts do.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from typing import Iterator, Optional

import numpy as np


@dataclass
class LassoBatch:
    idx: np.ndarray       # row ids, in walk/sample order
    b: np.ndarray         # (B, m) float32
    x_true: np.ndarray    # (B, n) float32
    x0: np.ndarray        # (B, n) float32


def x0_filename(split: str) -> str:
    """``test_sparsity_0.10.npy`` -> ``test_sparsity_0.10_x0.npy`` (data/lasso.py's rule)."""
    if not split.endswith(".npy"):
        raise ValueError("split must be a .npy filename, got {!r}".format(split))
    return split[:-len(".npy")] + "_x0.npy"


class LassoInstances:
    def __init__(self, data_dir: str, split: str, x0_mode: str = "aligned",
                 x0_stddev: float = 0.01, dtype=np.float32):
        if x0_mode not in ("aligned", "random"):
            raise ValueError("x0_mode must be 'aligned' or 'random', got {!r}".format(x0_mode))
        self.data_dir = data_dir
        self.split = split
        self.x0_mode = x0_mode
        self.x0_stddev = x0_stddev

        self.a = np.load(os.path.join(data_dir, "A.npy")).astype(dtype)
        data = np.load(os.path.join(data_dir, split)).astype(dtype)
        self.m, self.n = self.a.shape
        if data.shape[1] != self.m + self.n:
            raise ValueError(
                "{} has row width {}, expected {} (= m={} + n={} from {}/A.npy)".format(
                    os.path.join(data_dir, split), data.shape[1], self.m + self.n,
                    self.m, self.n, data_dir))
        self._data = data
        self.num_samples = data.shape[0]

        self._x0: Optional[np.ndarray] = None
        if x0_mode == "aligned":
            x0_path = os.path.join(data_dir, x0_filename(split))
            if not os.path.exists(x0_path):
                raise FileNotFoundError(
                    "{} not found -- x0_mode='aligned' requires the seeded x0 sibling "
                    "file generated by Benchmarking/data/lasso.py alongside {}.".format(
                        x0_path, split))
            self._x0 = np.load(x0_path).astype(dtype)
            if self._x0.shape != (self.num_samples, self.n):
                raise ValueError("{} has shape {}, expected {}".format(
                    x0_path, self._x0.shape, (self.num_samples, self.n)))

        w_path = os.path.join(data_dir, "W.npy")
        self.w_alista = np.load(w_path).astype(dtype) if os.path.exists(w_path) else None

    def _batch(self, idx: np.ndarray) -> LassoBatch:
        rows = self._data[idx]
        if self.x0_mode == "aligned":
            x0 = self._x0[idx]
        else:
            # Same op the library scripts use (tf.random.normal), so a seeded
            # run draws the same numbers. Imported lazily: this module must stay
            # TF-free for the fast tests.
            import tensorflow as tf
            x0 = tf.random.normal((len(idx), self.n), stddev=self.x0_stddev,
                                  dtype=tf.float32).numpy()
        return LassoBatch(idx=idx, b=rows[:, :self.m], x_true=rows[:, self.m:], x0=x0)

    def walk(self, batch_size: int) -> Iterator[LassoBatch]:
        """Deterministic pass over the split: ``ceil(num_samples / batch_size)`` chunks."""
        for start in range(0, self.num_samples, batch_size):
            yield self._batch(np.arange(start, min(start + batch_size, self.num_samples)))

    def num_chunks(self, batch_size: int) -> int:
        return -(-self.num_samples // batch_size)

    def sample(self, batch_size: int) -> LassoBatch:
        """Training batch with replacement from the global numpy RNG."""
        return self._batch(np.random.randint(0, self.num_samples, size=batch_size))
